import html2canvas from 'html2canvas'
import jsPDF from 'jspdf'

type ScorecardTotals = {
  met: number
  failed: number
  consideration: number
  na: number
}

type ScorecardRow = {
  label: string
  overall: string
  failedIndicators: string
  considerationIndicators: string
}

type ScorecardData = {
  title: string
  subtitle?: string
  totals: ScorecardTotals
  metaRows: Array<[string, string]>
  rows: ScorecardRow[]
}

type GovernanceAuditRow = {
  audit: string
  latestYear: string
  value: string
  label: string
  coverage: string
}

type GovernanceScorecardData = {
  title: string
  subtitle?: string
  metaRows: Array<[string, string]>
  auditRows: GovernanceAuditRow[]
  sglgTotals: ScorecardTotals
  sglgRows: ScorecardRow[]
}

function escapeHtml(value: string) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}


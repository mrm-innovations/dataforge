export async function openScorecardPdf(html: string, filename: string) {
  const pendingWindow = window.open('', '_blank')
  const container = document.createElement('div')
  container.innerHTML = html
  container.style.position = 'fixed'
  container.style.left = '-10000px'
  container.style.top = '0'
  container.style.width = '800px'
  container.style.background = 'white'
  document.body.appendChild(container)

  const canvas = await html2canvas(container, {
    scale: 2,
    backgroundColor: '#ffffff',
    useCORS: true,
    windowWidth: 800,
  })
  const imgData = canvas.toDataURL('image/png')
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const margin = 36
  const contentWidth = pageWidth - margin * 2
  const scale = contentWidth / canvas.width
  const pageHeightPx = (pageHeight - margin * 2) / scale - 20

  let yOffset = 0
  let pageIndex = 0
  while (yOffset < canvas.height) {
    const sliceHeight = Math.min(pageHeightPx, canvas.height - yOffset)
    const sliceCanvas = document.createElement('canvas')
    sliceCanvas.width = canvas.width
    sliceCanvas.height = sliceHeight
    const ctx = sliceCanvas.getContext('2d')
    if (!ctx) break
    ctx.drawImage(
      canvas,
      0,
      yOffset,
      canvas.width,
      sliceHeight,
      0,
      0,
      canvas.width,
      sliceHeight,
    )
    const sliceData = sliceCanvas.toDataURL('image/png')
    const sliceHeightPt = sliceHeight * scale
    if (pageIndex > 0) doc.addPage()
    doc.addImage(sliceData, 'PNG', margin, margin, contentWidth, sliceHeightPt)
    yOffset += sliceHeight
    pageIndex += 1
  }

  const blob = doc.output('blob')
  const url = URL.createObjectURL(blob)
  let opened = false
  if (pendingWindow) {
    pendingWindow.location.href = url
    opened = true
  } else {
    const win = window.open(url, '_blank')
    opened = !!win
  }
  if (!opened) {
    doc.save(filename)
  }
  setTimeout(() => URL.revokeObjectURL(url), 60_000)

  document.body.removeChild(container)
}
